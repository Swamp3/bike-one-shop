/**
 * Exports the shop's current catalog as plain JSON for the TriCon mock
 * (`backend/apps/tricon-mock`), which builds its TriBike items from it.
 *
 *   npx medusa exec ./src/scripts/export-tricon-mock-seed.ts
 *
 * Writes `backend/apps/tricon-mock/seed/catalog.json`. The output is
 * committed, so the mock runs without a shop database. Re-run it after the
 * shop catalog changes, then `npm run seed` in the mock workspace.
 */
import { mkdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import type { ExecArgs } from "@medusajs/framework/types"
import { ContainerRegistrationKeys } from "@medusajs/framework/utils"

type ExportedVariant = {
  id: string
  sku: string | null
  title: string
  options: { option: string; value: string }[]
  price_eur: number | null
}

type ExportedProduct = {
  id: string
  handle: string
  title: string
  description: string | null
  variants: ExportedVariant[]
}

const OUTPUT_PATH = path.resolve(
  process.cwd(),
  "..",
  "tricon-mock",
  "seed",
  "catalog.json"
)

export default async function exportTriconMockSeed({ container }: ExecArgs) {
  const query = container.resolve(ContainerRegistrationKeys.QUERY)
  const logger = container.resolve(ContainerRegistrationKeys.LOGGER)

  const { data: products } = await query.graph({
    entity: "product",
    fields: [
      "id",
      "handle",
      "title",
      "description",
      "variants.id",
      "variants.sku",
      "variants.title",
      "variants.options.value",
      "variants.options.option.title",
      "variants.prices.amount",
      "variants.prices.currency_code",
      "variants.prices.price_rules.attribute",
    ],
  })

  const exported: ExportedProduct[] = products
    .map((product: any) => ({
      id: product.id,
      handle: product.handle,
      title: product.title,
      description: product.description ?? null,
      variants: (product.variants ?? [])
        .map((variant: any) => {
          // Base EUR price: prefer one without rules (region/customer-group prices carry rules).
          const eurPrices = (variant.prices ?? []).filter(
            (price: any) => price?.currency_code?.toLowerCase() === "eur"
          )
          const basePrice =
            eurPrices.find((price: any) => !price.price_rules?.length) ??
            eurPrices[0]

          return {
            id: variant.id,
            sku: variant.sku ?? null,
            title: variant.title,
            options: (variant.options ?? [])
              .map((option: any) => ({
                option: option?.option?.title ?? "",
                value: option?.value ?? "",
              }))
              .sort((a: { option: string }, b: { option: string }) =>
                a.option.localeCompare(b.option)
              ),
            price_eur: basePrice ? Number(basePrice.amount) : null,
          }
        })
        .sort((a: ExportedVariant, b: ExportedVariant) =>
          (a.sku ?? a.id).localeCompare(b.sku ?? b.id)
        ),
    }))
    .sort((a: ExportedProduct, b: ExportedProduct) =>
      a.handle.localeCompare(b.handle)
    )

  const payload = {
    source: "medusa",
    note: "Generated by backend/apps/backend/src/scripts/export-tricon-mock-seed.ts. Demo catalog only, no customer data.",
    products: exported,
  }

  mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true })
  writeFileSync(OUTPUT_PATH, JSON.stringify(payload, null, 2) + "\n")

  const variantCount = exported.reduce((sum, p) => sum + p.variants.length, 0)
  logger.info(
    `Exported ${exported.length} products / ${variantCount} variants to ${OUTPUT_PATH}`
  )
}
